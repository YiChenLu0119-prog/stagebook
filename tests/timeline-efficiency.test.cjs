const assert=require('node:assert/strict');
const {createApp}=require('./app-harness.cjs');

(async()=>{
 const h=createApp(),{api,$,C}=h,q=api.state().lib.shows[0].songs[0];
 api.selectStep('c1');
 await api.action('timeline-selected-only');
 assert.equal($('#timelineSelectedOnly').getAttribute('aria-pressed'),'true');
 assert.match($('#bottomContent').innerHTML,/data-entity="a"/);
 assert.match($('#bottomContent').innerHTML,/data-entity="b"/,'Empty selection shows all tracks');
 api.seek(14.2);
 api.setTimelineZoom(3);
 $('#bottomContent').scrollLeft=470;
 api.setInspect('entity','a');
 assert.match($('#bottomContent').innerHTML,/data-entity="a"/);
 assert.doesNotMatch($('#bottomContent').innerHTML,/data-entity="b"/);
 assert.match($('#bottomContent').innerHTML,/data-timeline-bar="cue"/,'The step lane remains visible');
 assert.equal(api.state().current,14.2);
 assert.equal(api.state().zoom,3);
 assert.equal($('#bottomContent').scrollLeft,470);
 await api.action('timeline-selected-only');
 assert.match($('#bottomContent').innerHTML,/data-entity="b"/);

 q.mode='steps';
 q.cues[0].at=191;
 q.cues[1].at=200;
 const source=q.cues[0],move=source.moves[0];
 source.notes='Keep step notes';
 source.attachments=[{id:'image-original',file:'media/step.png',type:'image',mimeType:'image/png',name:'Blocking map',width:8,height:8,bytes:32}];
 move.points[1].c1={x:3,y:2};
 move.points[1].c2={x:8,y:2};
 const original=JSON.stringify(q);
 const expectedStart=C.position(q,'a',16.2);
 await api.action('edit-copy-playhead-dialog');
 assert.match($('#dialogTitle').textContent,/00:14\.2/,'Destination comes from the current playhead');
 assert.match($('#dialogBody').innerHTML,/Step One/);
 $('#copyPlayheadSource').value=source.id;
 $('#copyPlayheadConfirm').onclick();
 const copy=q.cues.find(c=>!['c1','c2'].includes(c.id));
 assert(copy);
 assert.equal(q.mode,'timed');
 assert.equal(copy.at,14.2);
 assert.equal(api.state().current,14.2);
 assert.equal(api.state().selectedCue,copy.id);
 assert.deepEqual(Array.from(q.cues.filter(c=>c!==copy),c=>c.at),[0,10]);
 assert.deepEqual(copy.moves.map(m=>m.entityId),source.moves.map(m=>m.entityId));
 assert.equal(copy.notes,source.notes);
 assert.equal(copy.moves[0].notes,move.notes);
 assert.equal(copy.moves[0].startOffset,move.startOffset);
 assert.equal(copy.moves[0].duration,move.duration);
 assert.notEqual(copy.moves[0].id,move.id);
 assert.deepEqual({...copy.moves[0].points[0]},expectedStart);
 assert.deepEqual(copy.moves[0].points[1],{...move.points[1],c1:{x:13,y:2}});
 assert.equal(copy.attachments[0].file,source.attachments[0].file);
 assert.notEqual(copy.attachments[0].id,source.attachments[0].id);
 assert.equal(api.state().history,1);
 api.undo();
 assert.equal(JSON.stringify(api.state().lib.shows[0].songs[0]),original);

 api.seek(4.8);
 const sourceBar=new h.Node();
 sourceBar.dataset.cue='c2';
 sourceBar.closest=selector=>selector==='[data-timeline-bar]'?sourceBar:null;
 api.openEditingContext({target:sourceBar,clientX:200,clientY:240,preventDefault(){}});
 assert.equal(api.state().selectedCue,'c2');
 assert.equal(api.state().current,4.8,'Right-clicking the source holds the playhead at the destination');
 assert.match($('#contextMenu').innerHTML,/edit-copy-to-playhead/);
 await api.action('edit-copy-to-playhead');
 assert.equal(api.state().lib.shows[0].songs[0].cues.find(c=>c.id===api.state().selectedCue).at,4.8);
 console.log('PASS: live actor filtering and copy to playhead with timing, routes, attachments and Undo');
})().catch(error=>{console.error(error);process.exitCode=1;});
