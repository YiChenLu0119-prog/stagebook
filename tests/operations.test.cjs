const assert=require('node:assert/strict');
const vm=require('node:vm');
const {createApp}=require('./app-harness.cjs');

(async()=>{
 const h=createApp();
 const read=code=>vm.runInContext(code,h.ctx);
 const original=JSON.stringify(h.api.state().lib);
 assert.equal(read('operationPrefs.focusTitleOnNewStep'),true,'The shipping default still focuses the title');
 h.api.seek(2);
 await h.api.action('transport-loop-a');
 h.api.seek(5.5);
 await h.api.action('transport-loop-b');
 assert.deepEqual(Array.from(read('[loop.start,loop.end]')),[2,5.5]);
 assert.match(h.$('#bottomContent').innerHTML,/timeline-loop-range/);
 assert.equal(JSON.stringify(h.api.state().lib),original);
 await read('play(true,true)');
 assert.equal(h.api.state().current,2,'Playing at B restarts the range from A');
 h.api.advance(4);
 assert.equal(h.api.state().current,2);
 assert.equal(h.api.state().playing,true);
 read("updateOperationPreference('repeatLoop',false)");
 h.api.advance(4);
 assert.equal(h.api.state().current,2);
 assert.equal(h.api.state().playing,false);
 await h.api.action('transport-loop-b');
 assert.equal(read('activeTransportLoop()'),null);
 assert.equal(read('transportLoopStart()'),2,'Tapping lit B turns the loop off and keeps A ready for a new endpoint');
 assert.equal(h.$('#markLoopB').getAttribute('aria-pressed'),'false');
 h.api.seek(6);
 await h.api.action('transport-loop-b');
 assert.equal(read('activeTransportLoop().end'),6);
 await h.api.action('transport-loop-a');
 assert.equal(read('activeTransportLoop()'),null);
 assert.equal(read('transportLoopStart()'),null,'Tapping lit A clears both the start and the range');
 assert.equal(h.$('#markLoopA').getAttribute('aria-pressed'),'false');
 assert.doesNotMatch(h.$('#bottomContent').innerHTML,/timeline-loop-range/);
 assert.equal(JSON.stringify(h.api.state().lib),original);

 const other=createApp();
 const otherRead=code=>vm.runInContext(code,other.ctx);
 const title=other.$('#inspector [data-field="title"]');
 otherRead('createStepAt(3)');
 assert.equal(other.document.activeElement,title);
 other.document.activeElement=other.document.body;
 otherRead("updateOperationPreference('focusTitleOnNewStep',false)");
 otherRead('createStepAt(6)');
 assert.equal(other.document.activeElement,other.document.body,'Turning off the option keeps keyboard focus in the workspace');
 console.log('PASS: explicit A and B markers, repeat and rewind-pause, nonpersistent production data, and opt-out title focus');
})().catch(error=>{console.error(error);process.exitCode=1;});
